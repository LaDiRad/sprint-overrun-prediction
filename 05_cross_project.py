import os
import numpy as np
import pandas as pd
import joblib
from sklearn.base import clone
from sklearn.model_selection import GroupKFold, train_test_split
from sklearn.metrics import (roc_auc_score, f1_score, precision_score,
                             recall_score, matthews_corrcoef, accuracy_score)
from imblearn.pipeline import Pipeline as ImbPipeline
from imblearn.over_sampling import SMOTE
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import (RandomForestClassifier, GradientBoostingClassifier,
                              AdaBoostClassifier)
from sklearn.neural_network import MLPClassifier
from xgboost import XGBClassifier
from scipy.stats import spearmanr, wilcoxon
from statsmodels.stats.multitest import multipletests

RANDOM_STATE = 42
PROJECT = '/content/drive/MyDrive/ages-sprint-overrun/pipeline'
IN1 = f'{PROJECT}/01_data_prep'
IN3 = f'{PROJECT}/03_optimization'
OUT = f'{PROJECT}/06_cross_project'
os.makedirs(OUT, exist_ok=True)

df = pd.read_csv(f'{IN1}/df_final.csv', parse_dates=['Created At'])
FEATURE_COLS = joblib.load(f'{IN1}/feature_cols.pkl')
MODEL_FINAL = joblib.load(f'{IN3}/model_final_name.pkl')
modele_opt = joblib.load(f'{IN3}/modele_optimizate.pkl')
thresholds = joblib.load(f'{IN3}/thresholds.pkl')

X = df[FEATURE_COLS]
y = df['exceed_sprint']

print(f'Final model (chronological protocol): {MODEL_FINAL}')
print(f'{len(df)} rows, {df["Repository"].nunique()} repositories')

# Model definitions

def pipe(clf, scale=False):
    steps = [('smote', SMOTE(random_state=RANDOM_STATE))]
    if scale:
        steps.append(('scaler', StandardScaler()))
    steps.append(('clf', clf))
    return ImbPipeline(steps)

MODEL_BUILDERS = {
    'Random Forest': lambda: pipe(RandomForestClassifier(n_estimators=200, max_depth=8,
                                   random_state=RANDOM_STATE, n_jobs=-1)),
    'Gradient Boosting': lambda: pipe(GradientBoostingClassifier(n_estimators=200, max_depth=4,
                                       learning_rate=0.05, random_state=RANDOM_STATE)),
    'XGBoost': lambda: pipe(XGBClassifier(n_estimators=300, max_depth=5, learning_rate=0.05,
                            subsample=0.8, colsample_bytree=0.8, random_state=RANDOM_STATE,
                            n_jobs=-1, eval_metric='logloss')),
    'MLP': lambda: pipe(MLPClassifier(hidden_layer_sizes=(100, 50), activation='relu',
                        max_iter=500, early_stopping=True, n_iter_no_change=10,
                        random_state=RANDOM_STATE), scale=True),
    'AdaBoost': lambda: pipe(AdaBoostClassifier(n_estimators=100, learning_rate=0.1,
                             random_state=RANDOM_STATE)),
    'Logistic Regression': lambda: pipe(LogisticRegression(max_iter=1000,
                                        random_state=RANDOM_STATE), scale=True),
    'Decision Tree': lambda: pipe(DecisionTreeClassifier(max_depth=5,
                                  random_state=RANDOM_STATE)),
}
MIN_ISSUES_LORO = 100
MIN_ISSUES_REPL = 400
print(f'{len(MODEL_BUILDERS)} models defined')

# Leave-repository-out (5-fold GroupKFold, all 7 models)

groups = df['Repository']
N_SPLITS = 5
gkf = GroupKFold(n_splits=N_SPLITS)

rows = []
for model_name, builder in MODEL_BUILDERS.items():
    for fold, (tr_idx, te_idx) in enumerate(gkf.split(X, y, groups=groups), 1):
        repos_test = sorted(groups.iloc[te_idx].unique())
        model = builder()
        model.fit(X.iloc[tr_idx], y.iloc[tr_idx])
        proba = model.predict_proba(X.iloc[te_idx])[:, 1]
        pred  = (proba >= 0.5).astype(int)

        rows.append({
            'Model': model_name,
            'Fold': fold,
            'Held-out repositories': ', '.join(repos_test),
            'N test': len(te_idx),
            'Test AUC': round(roc_auc_score(y.iloc[te_idx], proba), 3),
            'Precision (Exceeds)': round(precision_score(y.iloc[te_idx], pred, pos_label=1, zero_division=0), 3),
            'Recall (Exceeds)': round(recall_score(y.iloc[te_idx], pred, pos_label=1), 3),
            'F1 (Exceeds)': round(f1_score(y.iloc[te_idx], pred, pos_label=1, zero_division=0), 3),
            'MCC': round(matthews_corrcoef(y.iloc[te_idx], pred), 3),
            'Accuracy (weighted)': round(accuracy_score(y.iloc[te_idx], pred), 3),
        })
    print(f'{model_name}: done')

df_cross = pd.DataFrame(rows)
df_cross.to_csv(f'{OUT}/table_cross_project_folds_all_models.csv', index=False)

# Cross-project vs. chronological summary

df_chrono_final = pd.read_csv(f'{IN3}/table_final_test_results.csv')
chrono_row = df_chrono_final[df_chrono_final['Model'] == MODEL_FINAL].iloc[0]
df_cross_final_model = df_cross[df_cross['Model'] == MODEL_FINAL]

summary = pd.DataFrame([
    {'Evaluation protocol': 'Chronological split (same projects)',
     'Mean/Test AUC': chrono_row['Test AUC'], 'Mean MCC': chrono_row['MCC']},
    {'Evaluation protocol': f'Cross-project ({N_SPLITS}-fold, held-out repos)',
     'Mean/Test AUC': round(df_cross_final_model['Test AUC'].mean(), 3),
     'Mean MCC': round(df_cross_final_model['MCC'].mean(), 3)},
])
summary.to_csv(f'{OUT}/table_cross_project_vs_chronological.csv', index=False)
print(summary.to_string(index=False))

# Repository contextual profile

profile = df.groupby('Repository').agg(
    n_issues=('exceed_sprint', 'size'),
    exceed_rate=('exceed_sprint', 'mean'),
    median_duration=('Time_Taken_Days', 'median'),
    n_contributors=('n_assignees', 'nunique'),
    mean_labels=('n_labels', 'mean'),
    pct_with_milestone=('has_milestone', 'mean'),
    mean_body_len=('log_body_len', 'mean'),
    span_days=('Created At', lambda s: (s.max() - s.min()).days),
).round(3)
profile['issues_per_year'] = (profile['n_issues'] / (profile['span_days']/365)).round(1)
profile.to_csv(f'{OUT}/table_repository_profile.csv')
profile.reset_index().sort_values('n_issues', ascending=False).to_string(index=False)

# Correlation of cross-project MCC with contextual factors

loro_final = (df_cross[df_cross['Model'] == MODEL_FINAL]
              .assign(Repository=lambda d: d['Held-out repositories'])
              [['MCC']])

# MCC is per-fold (multiple repos per fold)


rows_loro1 = []
for repo in sorted(df['Repository'].unique()):
    te = df['Repository'] == repo
    if te.sum() < MIN_ISSUES_LORO:
        continue
    if y[te].nunique() < 2:
        continue
    m = clone(modele_opt[MODEL_FINAL])
    m.fit(X[~te], y[~te])
    proba = m.predict_proba(X[te])[:, 1]
    pred  = (proba >= thresholds[MODEL_FINAL]).astype(int)
    rows_loro1.append({
        'Repository': repo, 'N': int(te.sum()),
        'Test AUC': round(roc_auc_score(y[te], proba), 3),
        'MCC': round(matthews_corrcoef(y[te], pred), 3),
        'Recall': round(recall_score(y[te], pred, pos_label=1), 3),
    })
loro = pd.DataFrame(rows_loro1).sort_values('MCC', ascending=False)
loro.to_csv(f'{OUT}/table_leave_one_repo_out.csv', index=False)

merged = loro.merge(profile, left_on='Repository', right_index=True)
corr_rows = []
for col in ['n_issues','exceed_rate','n_contributors','mean_labels',
            'pct_with_milestone','issues_per_year','median_duration']:
    rho, p = spearmanr(merged['MCC'], merged[col])
    corr_rows.append({'Factor': col, 'rho': round(rho, 3), 'p-value': round(p, 4)})
    print(f'MCC vs {col:20s}: rho={rho:+.3f}, p={p:.3f}')

pd.DataFrame(corr_rows).to_csv(f'{OUT}/table_contextual_correlations.csv', index=False)

# Within-repository protocol replication (all 7 models)

all_rows = []

for model_name, builder in MODEL_BUILDERS.items():
    print(f'Model: {model_name}')
    for repo in sorted(df['Repository'].unique()):
        sub = df[df['Repository'] == repo].sort_values('Created At').reset_index(drop=True)
        if len(sub) < MIN_ISSUES_REPL:
            continue

        Xr, yr = sub[FEATURE_COLS], sub['exceed_sprint']
        k = int(len(sub) * 0.8)

        m1 = clone(builder())
        m1.fit(Xr[:k], yr[:k])
        if yr[k:].nunique() < 2:
            continue
        auc_chrono = roc_auc_score(yr[k:], m1.predict_proba(Xr[k:])[:, 1])

        Xtr, Xte, ytr, yte = train_test_split(
            Xr, yr, test_size=(len(sub) - k) / len(sub),
            stratify=yr, random_state=RANDOM_STATE
        )
        m2 = clone(builder())
        m2.fit(Xtr, ytr)
        if yte.nunique() < 2:
            continue
        auc_random = roc_auc_score(yte, m2.predict_proba(Xte)[:, 1])

        all_rows.append({
            'Model': model_name, 'Repository': repo, 'N': len(sub),
            'AUC random': round(auc_random, 3),
            'AUC chronological': round(auc_chrono, 3),
            'Delta': round(auc_chrono - auc_random, 3),
        })

df_replication_all = pd.DataFrame(all_rows)
df_replication_all.to_csv(f'{OUT}/table_within_repo_replication_all_models.csv', index=False)
print(f'Total rows: {len(df_replication_all)}')

# Aggregate Wilcoxon test per model, Holm-corrected

wilcoxon_rows = []
for model_name in MODEL_BUILDERS.keys():
    sub = df_replication_all[df_replication_all['Model'] == model_name]
    n_repos = len(sub)
    if n_repos < 2:
        continue
    n_negative = (sub['Delta'] < 0).sum()
    stat, p = wilcoxon(sub['AUC chronological'], sub['AUC random'])
    wilcoxon_rows.append({
        'Model': model_name, 'N repositories': n_repos,
        'Negative Delta (chrono < random)': f'{n_negative}/{n_repos}',
        'Wilcoxon W': round(stat, 3), 'p-value': round(p, 4),
    })

df_wilcoxon_all = pd.DataFrame(wilcoxon_rows)
reject, p_holm, _, _ = multipletests(df_wilcoxon_all['p-value'], alpha=0.05, method='holm')
df_wilcoxon_all['p (Holm)'] = p_holm.round(4)
df_wilcoxon_all['Significant'] = reject
df_wilcoxon_all = df_wilcoxon_all.sort_values('p-value')
df_wilcoxon_all.to_csv(f'{OUT}/table_within_repo_wilcoxon_all_models.csv', index=False)

print(df_wilcoxon_all.to_string(index=False))
print(f'\nAll outputs saved to {OUT}')