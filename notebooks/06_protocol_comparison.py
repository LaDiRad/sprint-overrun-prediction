# Top-3 pairwise Wilcoxon comparisons, computed separately within each of
# the three evaluation protocols (A=permissive, B=medium, C=rigorous)

from scipy.stats import wilcoxon
from sklearn.metrics import matthews_corrcoef
from sklearn.base import clone
from itertools import combinations
import numpy as np
import pandas as pd

def mcc_per_fold(model, X, y, cv, threshold=0.5):
    out = []
    for tr, va in cv.split(X, y):
        m = clone(model)
        m.fit(X.iloc[tr], y.iloc[tr])
        proba = m.predict_proba(X.iloc[va])[:, 1]
        out.append(matthews_corrcoef(y.iloc[va], (proba >= threshold).astype(int)))
    return np.array(out)

def top3_pairwise_wilcoxon(modele_opt, thresholds, X_train, y_train, cv, df_final, protocol_name):
    top3 = df_final.sort_values('MCC', ascending=False).head(3)['Model'].tolist()
    print(f'{protocol_name} — Top 3: {top3}')

    mcc_scores = {m: mcc_per_fold(modele_opt[m], X_train, y_train, cv, thresholds[m]) for m in top3}

    rows = []
    for m1, m2 in combinations(top3, 2):
        s, p = wilcoxon(mcc_scores[m1], mcc_scores[m2])
        rows.append({
            'Protocol': protocol_name,
            'Comparison': f'{m1} vs {m2}',
            'Mean MCC (1)': round(mcc_scores[m1].mean(), 3),
            'Mean MCC (2)': round(mcc_scores[m2].mean(), 3),
            'Statistic': round(s, 3),
            'p-value': round(p, 4),
        })
    return pd.DataFrame(rows)

# Protocol A: permissive (random split, test-calibrated threshold)
df_permissive = top3_pairwise_wilcoxon(modele_opt_A, thresholds_A, X_train_A, y_train_A, cv_A,
                                       df_final_A, 'Permissive (A)')

# Protocol B: medium (random split, OOF-calibrated threshold)
df_medium = top3_pairwise_wilcoxon(modele_opt_B, thresholds_B, X_train_A, y_train_A, cv_A,
                                   df_final_B, 'Medium (B)')

# Protocol C: rigorous (chronological split, OOF-calibrated threshold)
df_rigorous = top3_pairwise_wilcoxon(modele_opt_C, thresholds_C, X_train_B, y_train_B, cv_C,
                                     df_final_C, 'Rigorous (C)')

df_all_pairwise = pd.concat([df_permissive, df_medium, df_rigorous], ignore_index=True)

from statsmodels.stats.multitest import multipletests
reject, p_corrected, _, _ = multipletests(df_all_pairwise['p-value'], alpha=0.05, method='holm')
df_all_pairwise['p_Holm'] = p_corrected.round(4)
df_all_pairwise['Significant'] = reject

print(df_all_pairwise.to_string(index=False))

