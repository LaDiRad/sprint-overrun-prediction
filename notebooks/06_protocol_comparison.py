# Correation and top 10 overlap

from scipy.stats import spearmanr

rho_rand_chrono, p_rc = spearmanr(df_features['Rank (Random)'], df_features['Rank (Chronological)'])
rho_rand_oof, p_ro = spearmanr(df_features['Rank (Random)'], df_features['Rank (Random+OOF)'])
rho_oof_chrono, p_oc = spearmanr(df_features['Rank (Random+OOF)'], df_features['Rank (Chronological)'])

def top_k_overlap(rank1, rank2, k=10):
    top1 = set(rank1[rank1 <= k].index)
    top2 = set(rank2[rank2 <= k].index)
    return len(top1 & top2) / k

overlap_rc = top_k_overlap(df_features['Rank (Random)'], df_features['Rank (Chronological)'])


print(f'Random vs Chronological:   ρ={rho_rand_chrono:.3f}, p={p_rc:.4f}')
print(f'Random vs Random+OOF:      ρ={rho_rand_oof:.3f}, p={p_ro:.4f}')
print(f'Random+OOF vs Chronological: ρ={rho_oof_chrono:.3f}, p={p_oc:.4f}')
print(f'Top-10 overlap (Random vs Chronological): {overlap_rc*100:.0f}%')

