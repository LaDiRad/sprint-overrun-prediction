# Save results

joblib.dump((X_train, X_test, y_train, y_test), f'{OUT}/split_chronological.pkl')
joblib.dump(cv_ts, f'{OUT}/cv_scheme.pkl')
joblib.dump(rezultate_base, f'{OUT}/rezultate_base.pkl')

