# Within-repository protocol replication

from sklearn.base import clone
from sklearn.metrics import roc_auc_score, matthews_corrcoef, f1_score, recall_score

rows = []
for repo in sorted(df['Repository'].unique()):
    te = df['Repository'] == repo
    if te.sum() < 100:            # skip RxJava, backbone
        continue
    m = clone(modele_opt['Random Forest'])
    m.fit(X[~te], y[~te])
    proba = m.predict_proba(X[te])[:, 1]
    pred  = (proba >= thresholds['Random Forest']).astype(int)
    if y[te].nunique() < 2:
        continue
    rows.append({
        'Repository': repo,
        'N': int(te.sum()),
        'Exceed rate': round(y[te].mean(), 3),
        'Test AUC': round(roc_auc_score(y[te], proba), 3),
        'MCC': round(matthews_corrcoef(y[te], pred), 3),
        'Recall': round(recall_score(y[te], pred, pos_label=1), 3),
    })
loro = pd.DataFrame(rows).sort_values('MCC', ascending=False)

# Correlate cross-project MCC (leave-repository-out, Random Forest) against
# repository-level contextual factors, to identify what distinguishes
# repositories where the model generalizes well from those where it does not

from scipy.stats import spearmanr

merged = loro.merge(profile, left_on='Repository', right_index=True)
for col in ['n_issues','exceed_rate','n_contributors','mean_labels',
            'pct_with_milestone','issues_per_year','median_duration']:
    rho, p = spearmanr(merged['MCC'], merged[col])
    print(f'MCC vs {col:20s}: rho={rho:+.3f}, p={p:.3f}')

# Within-repository protocol replication

rows = []
for repo in sorted(df['Repository'].unique()):
    sub = df[df['Repository'] == repo].sort_values('Created At').reset_index(drop=True)
    if len(sub) < 400:
        continue
    Xr, yr = sub[FEATURE_COLS], sub['depaseste_sprint']
    k = int(len(sub) * 0.8)

    # chronological
    m1 = clone(modele_opt['Random Forest']); m1.fit(Xr[:k], yr[:k])
    auc_chrono = roc_auc_score(yr[k:], m1.predict_proba(Xr[k:])[:,1])

    # random
    Xtr, Xte, ytr, yte = train_test_split(Xr, yr, test_size=0.2,
                                          stratify=yr, random_state=42)
    m2 = clone(modele_opt['Random Forest']); m2.fit(Xtr, ytr)
    auc_random = roc_auc_score(yte, m2.predict_proba(Xte)[:,1])

    rows.append({'Repository': repo, 'N': len(sub),
                 'AUC random': round(auc_random,3),
                 'AUC chronological': round(auc_chrono,3),
                 'Delta': round(auc_chrono - auc_random,3)})

repl = pd.DataFrame(rows)
from scipy.stats import wilcoxon
s, p = wilcoxon(repl['AUC chronological'], repl['AUC random'])
print(repl.to_string(index=False))
print(f'\nWilcoxon across {len(repl)} repositories: statistic={s}, p={p:.4f}')