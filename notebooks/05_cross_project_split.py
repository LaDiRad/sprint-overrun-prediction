# Repository-level GroupKFold

from sklearn.model_selection import GroupKFold
from imblearn.pipeline import Pipeline as ImbPipeline
from imblearn.over_sampling import SMOTE
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier, AdaBoostClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from xgboost import XGBClassifier
from sklearn.metrics import (roc_auc_score, f1_score, precision_score,
                             recall_score, matthews_corrcoef)

def pipe(clf, scale=False):
    steps = [('smote', SMOTE(random_state=RANDOM_STATE))]
    if scale:
        steps.append(('scaler', StandardScaler()))
    steps.append(('clf', clf))
    return ImbPipeline(steps)

MODEL_BUILDERS = {
    'Random Forest': lambda: pipe(RandomForestClassifier(n_estimators=200, max_depth=8,
                                   random_state=RANDOM_STATE, n_jobs=-1)),
    'Gradient Boosting': lambda: pipe(GradientBoostingClassifier(n_estimators=200, max_depth=4,
                                       learning_rate=0.05, random_state=RANDOM_STATE)),
    'XGBoost': lambda: pipe(XGBClassifier(n_estimators=300, max_depth=5, learning_rate=0.05,
                            subsample=0.8, colsample_bytree=0.8, random_state=RANDOM_STATE,
                            n_jobs=-1, eval_metric='logloss')),
    'MLP': lambda: pipe(MLPClassifier(hidden_layer_sizes=(100, 50), activation='relu',
                        max_iter=500, early_stopping=True, n_iter_no_change=10,
                        random_state=RANDOM_STATE), scale=True),
    'AdaBoost': lambda: pipe(AdaBoostClassifier(n_estimators=100, learning_rate=0.1,
                             random_state=RANDOM_STATE)),
    'Logistic Regression': lambda: pipe(LogisticRegression(max_iter=1000,
                                        random_state=RANDOM_STATE), scale=True),
    'Decision Tree': lambda: pipe(DecisionTreeClassifier(max_depth=5,
                                  random_state=RANDOM_STATE)),
}


X = df[FEATURE_COLS]
y = df['depaseste_sprint']
groups = df['Repository']

N_SPLITS = 5
gkf = GroupKFold(n_splits=N_SPLITS)

rows = []
for model_name, builder in MODEL_BUILDERS.items():
    for fold, (tr_idx, te_idx) in enumerate(gkf.split(X, y, groups=groups), 1):
        repos_test = sorted(groups.iloc[te_idx].unique())
        model = builder()
        model.fit(X.iloc[tr_idx], y.iloc[tr_idx])
        proba = model.predict_proba(X.iloc[te_idx])[:, 1]
        pred  = (proba >= 0.5).astype(int)

        rows.append({
            'Model': model_name,
            'Fold': fold,
            'Held-out repositories': ', '.join(repos_test),
            'N test': len(te_idx),
            'Test AUC': round(roc_auc_score(y.iloc[te_idx], proba), 3),
            'F1 (Exceeds)': round(f1_score(y.iloc[te_idx], pred, pos_label=1, zero_division=0), 3),
            'Recall (Exceeds)': round(recall_score(y.iloc[te_idx], pred, pos_label=1), 3),
            'MCC': round(matthews_corrcoef(y.iloc[te_idx], pred), 3),
        })
    print(f'{model_name}: done')

df_cross = pd.DataFrame(rows)
df_cross.to_csv(f'{OUT}/table_cross_project_folds_all_models.csv', index=False)

