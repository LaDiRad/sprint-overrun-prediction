from google.colab import drive
drive.mount('/content/drive')

import os, ast, time
import numpy as np
import pandas as pd

RANDOM_STATE = 42
np.random.seed(RANDOM_STATE)

PROJECT = '/content/drive/MyDrive/ages-sprint-overrun/pipeline'
OUT = f'{PROJECT}/01_data_prep'
os.makedirs(OUT, exist_ok=True)

print('Output folder:', OUT)

"""## Load raw data"""

df = pd.read_csv(f'{PROJECT}/../Raw_AgES_Dataset.csv')
# change the path above if the raw CSV lives elsewhere in Drive
print(f'Raw: {len(df)} rows, {len(df.columns)} columns, '
      f'{df["Repository"].nunique()} repositories')

df['Created At'] = pd.to_datetime(df['Created At'], utc=True, errors='coerce')
df['Closed At']  = pd.to_datetime(df['Closed At'],  utc=True, errors='coerce')
df['Time_Taken_Days'] = (df['Closed At'] - df['Created At']).dt.total_seconds() / 86400

n0 = len(df)
df = df[df['Time_Taken_Days'] >= 0].dropna(subset=['Time_Taken_Days', 'Created At'])
n1 = len(df)

PRAG_OUTLIER = 365
df = df[df['Time_Taken_Days'] <= PRAG_OUTLIER].reset_index(drop=True)
n2 = len(df)

print(f'Raw:                 {n0}')
print(f'Valid durations:     {n1}  (-{n0-n1})')
print(f'Duration <= {PRAG_OUTLIER}d:      {n2}  (-{n1-n2})')

# Maturity buffer & sensitivity check

MATURITY_BUFFER_DAYS = 180
data_max_close = df['Closed At'].max()
cutoff = data_max_close - pd.Timedelta(days=MATURITY_BUFFER_DAYS)
print(f'Latest recorded closure: {data_max_close}')
print(f'Maturity cutoff:         {cutoff}')

n_before = len(df)
df = df[df['Created At'] <= cutoff].reset_index(drop=True)
n_after = len(df)
print(f'Removed {n_before - n_after} issues created after cutoff '
      f'({100*(n_before-n_after)/n_before:.1f}%)')
print(f'Remaining: {n_after}')

df['_year'] = df['Created At'].dt.to_period('Q').astype(str)
tmp = df.copy()
tmp['exceed_sprint_14'] = (tmp['Time_Taken_Days'] > 14).astype(int)
print('Exceed-sprint rate by quarter (AFTER maturity filter):')
print(tmp.groupby('_year')['exceed_sprint_14'].agg(['mean', 'count']).tail(12))
df = df.drop(columns=['_year'])

# Set sprint timeframe

SPRINT_DAYS = 14
df['exceed_sprint'] = (df['Time_Taken_Days'] > SPRINT_DAYS).astype(int)
print(f'Target (14-day threshold): {df["exceed_sprint"].mean()*100:.1f}% exceed-sprint')

cleaning_log = pd.DataFrame([
    {'Step': 'Raw dataset', 'N': n0},
    {'Step': 'Valid durations', 'N': n1},
    {'Step': f'Duration <= {PRAG_OUTLIER}d', 'N': n2},
    {'Step': f'Maturity filter ({MATURITY_BUFFER_DAYS}d buffer)', 'N': n_after},
])
cleaning_log.to_csv(f'{OUT}/table_cleaning_log.csv', index=False)
cleaning_log

# Featuring engineering
# Field Comments was excluded

def parse_list(val):
    if pd.isna(val) or str(val).strip() in ('', '[]', 'nan'):
        return []
    try:
        r = ast.literal_eval(str(val))
        return r if isinstance(r, list) else [r]
    except Exception:
        return [str(val)]

df['n_assignees']      = df['Assignees'].apply(lambda x: len(parse_list(x)))
df['n_labels']         = df['Labels'].apply(lambda x: len(parse_list(x)))
df['is_feature_label'] = df['Labels'].apply(
    lambda x: int(any('feature' in str(l).lower() for l in parse_list(x))))
df['title_len']        = df['Title'].fillna('').apply(len)
df['Contributors Expertise'] = pd.to_numeric(df['Contributors Expertise'], errors='coerce')
df['has_milestone']    = df['Milestone'].notna().astype(int)
df['created_hour']     = df['Created At'].dt.hour
df['created_dayofweek']= df['Created At'].dt.dayofweek

df['body_len']     = df['Body'].fillna('').apply(len)
df['log_body_len'] = np.log1p(df['body_len'])

df['cat_bug']         = (df['Category'] == 'Bug').astype(int)
df['cat_feature']     = (df['Category'] == 'Feature').astype(int)
df['cat_improvement'] = (df['Category'] == 'Improvement').astype(int)

COMPONENTE = ['ui','backend','api','network','security','database','authentication','performance']
for comp in COMPONENTE:
    df[f'comp_{comp}'] = df['Component'].fillna('').str.contains(comp, case=False).astype(int)

print('Base features created')
print(f'has_milestone=1 for {df["has_milestone"].mean()*100:.1f}% of issues')

# Featuring engineering
# complexity, urgency & negative words

complexity_words = ['refactor', 'breaking change', 'breaking', 'redesign', 'rewrite',
                    'architecture', 'migration', 'deprecat', 'incompatible', 'blocked',
                    'depends', 'dependency', 'complex', 'investigat', 'unclear', 'discussion']
urgency_words    = ['urgent', 'critical', 'asap', 'blocker', 'regression', 'security']
neg_words        = ['error','fail','broken','crash','bug','problem','issue','wrong',
                    'cannot', "doesn't", 'not working', 'unexpected']

def count_words(text, words):
    t = str(text).lower()
    return sum(t.count(w) for w in words)

df['n_complexity_words'] = df['Body'].apply(lambda x: count_words(x, complexity_words))
df['n_urgency_words']    = df['Body'].apply(lambda x: count_words(x, urgency_words))
df['n_negative_words']   = df['Body'].apply(lambda x: count_words(x, neg_words))
df['body_has_steps']     = df['Body'].fillna('').str.contains(
    r'step|repro|reproduce|expected|actual', case=False, na=False, regex=True).astype(int)

print('NLP features created')

# Assignee history - only issues closed before creation time of the current issues are used to calculated contributors experise

df['first_assignee'] = df['Assignees'].apply(lambda x: parse_list(x)[0] if parse_list(x) else 'none')
df = df.sort_values('Created At').reset_index(drop=True)

df['assignee_avg_duration'] = np.nan
df['assignee_task_count']   = 0
df['assignee_open_tasks']   = 0

t0 = time.time()
for a, grup in df.groupby('first_assignee'):
    idxs = grup.index
    cr  = grup['Created At'].values
    cl  = grup['Closed At'].values
    dur = grup['Time_Taken_Days'].values
    for i, idx in enumerate(idxs):
        c = cr[i]
        closed_before = cl < c
        if closed_before.any():
            df.at[idx, 'assignee_avg_duration'] = dur[closed_before].mean()
            df.at[idx, 'assignee_task_count']   = int(closed_before.sum())
        df.at[idx, 'assignee_open_tasks'] = int(((cr < c) & (cl > c)).sum())

mediana_globala = df['Time_Taken_Days'].median()
df['assignee_avg_duration'] = df['assignee_avg_duration'].fillna(mediana_globala)

print(f'Computed in {time.time()-t0:.1f}s')
print(f'First-time assignees (imputed with median): {(df["assignee_task_count"]==0).sum()}')

# Missing values

lipsa = df.isnull().sum()
print('Missing before imputation:')
print(lipsa[lipsa > 0])

# Contributors Expertise imputed with median

df['Contributors Expertise'] = df['Contributors Expertise'].fillna(
    df['Contributors Expertise'].median())

# Final features set

FEATURE_COLS = [
    'log_body_len', 'Contributors Expertise',
    'n_labels', 'has_milestone', 'is_feature_label', 'title_len',
    'created_dayofweek', 'created_hour', 'n_assignees',
    'cat_bug', 'cat_feature', 'cat_improvement',
] + [f'comp_{c}' for c in COMPONENTE] + [
    'n_complexity_words', 'n_urgency_words', 'body_has_steps', 'n_negative_words',
    'assignee_avg_duration', 'assignee_task_count', 'assignee_open_tasks',
]

print(f'{len(FEATURE_COLS)} features')
print(f'Missing values in feature set: {df[FEATURE_COLS].isnull().sum().sum()} (must be 0)')

# Multicollinearity check

corr = df[FEATURE_COLS].corr()
mask = np.triu(np.ones(corr.shape), k=1).astype(bool)
perechi = corr.where(mask).stack().reset_index()
perechi.columns = ['Feature 1', 'Feature 2', 'r']
perechi['abs_r'] = perechi['r'].abs()

redundante = perechi[perechi['abs_r'] > 0.90].sort_values('abs_r', ascending=False)
print('Top correlations:')
print(perechi.sort_values('abs_r', ascending=False).head(10)[['Feature 1','Feature 2','r']].to_string(index=False))

if len(redundante):
    de_eliminat = redundante['Feature 2'].unique().tolist()
    FEATURE_COLS = [f for f in FEATURE_COLS if f not in de_eliminat]
    print(f'\nDropped (|r|>0.90): {de_eliminat}')
else:
    print('\nNo pair exceeds |r|=0.90 — nothing dropped')

print(f'Final feature count: {len(FEATURE_COLS)}')

# Repository distribution on projects

repo_counts = df['Repository'].value_counts()
print(f'{df["Repository"].nunique()} repositories')
print(repo_counts)
repo_counts.to_csv(f'{OUT}/table_repository_counts.csv')

# Save outputs

import joblib

# full processed dataframe, keeps Repository + Created At for later stages
keep_cols = FEATURE_COLS + ['exceed_sprint', 'Time_Taken_Days',
                             'Created At', 'Repository']
df_final = df[keep_cols].copy()
df_final.to_csv(f'{OUT}/df_final.csv', index=False)

joblib.dump(FEATURE_COLS, f'{OUT}/feature_cols.pkl')
joblib.dump(MATURITY_BUFFER_DAYS, f'{OUT}/maturity_buffer.pkl')
joblib.dump(SPRINT_DAYS, f'{OUT}/sprint_threshold.pkl')

print(f' Saved to {OUT}')
print(f'   df_final.csv: {len(df_final)} rows, {len(df_final.columns)} columns')