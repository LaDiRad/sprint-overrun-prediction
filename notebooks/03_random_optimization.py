from sklearn.metrics import precision_recall_curve, matthews_corrcoef

def prag_pe_test_PERMISIV(model, X_test, y_test, nume=''):
    proba = model.predict_proba(X_test)[:, 1]
    p, r, thr = precision_recall_curve(y_test, proba)
    f1 = 2 * (p[:-1] * r[:-1]) / (p[:-1] + r[:-1] + 1e-10)
    i = int(np.argmax(f1))
    print(f'{nume:22s} threshold={thr[i]:.4f} (fit on TEST, permissive)  '
          f'P={p[i]:.3f} R={r[i]:.3f} F1={f1[i]:.3f}')
    return float(thr[i])

thresholds = {}
for nume, model in modele_opt.items():
    thresholds[nume] = prag_pe_test_PERMISIV(model, X_test, y_test, nume)

joblib.dump(thresholds, f'{OUT}/thresholds.pkl')



